@Test func matchQualityOrdersExactPrefixWordStartSubstringSubsequence() throws {
    let exact = try #require(QuickSwitch.score(query: "beta", text: "beta"))
    let prefix = try #require(QuickSwitch.score(query: "bet", text: "beta-api"))
    let word = try #require(QuickSwitch.score(query: "api", text: "beta-api"))
    let sub = try #require(QuickSwitch.score(query: "eta", text: "beta"))
    let seq = try #require(QuickSwitch.score(query: "bai", text: "beta-api"))
    #expect(exact > prefix && prefix > word && word > sub && sub > seq)
    #expect(QuickSwitch.score(query: "xyz", text: "beta") == nil)
    #expect(QuickSwitch.score(query: "atb", text: "beta") == nil)   // order matters
    // Case-, diacritic- and width-insensitive.
    #expect(QuickSwitch.score(query: "CAFE", text: "café-ünïcode") != nil)
    #expect(QuickSwitch.score(query: "unic", text: "café-ünïcode") != nil)
    // Word starts and runs beat scattered letters.
    #expect(try #require(QuickSwitch.score(query: "fl", text: "fix-login")) > (QuickSwitch.score(query: "fn", text: "fix-login") ?? 0))
}

@Test func rankingBoostsNeedsYouThenUnreadThenRecent() {
    let now = 1_800_000_000
    let items = [
        QuickSwitch.Item(id: "a", title: "muxbar-e2e-alpha", host: "This Mac", lastViewed: now - 30),
        QuickSwitch.Item(id: "b", title: "muxbar-e2e-beta", group: "e2e-grp", host: "devbox", lastViewed: now - 7200),
        QuickSwitch.Item(id: "g", title: "muxbar-e2e-gamma", host: "devbox", needsYou: true, waitingSince: now - 100),
        QuickSwitch.Item(id: "d", title: "muxbar-e2e-delta", host: "devbox", unread: true, finishedAt: now - 50),
        QuickSwitch.Item(id: "new", kind: .command, title: "New Session…"),
    ]
    #expect(QuickSwitch.rank(items, query: "bet", now: now).first?.item.id == "b")
    #expect(QuickSwitch.rank(items, query: "grp bet", now: now).first?.item.id == "b")
    #expect(QuickSwitch.rank(items, query: "grp zzz", now: now).isEmpty)          // every word must match
    #expect(QuickSwitch.rank(items, query: "devb gam", now: now).first?.item.id == "g")
    // Same match quality: needs you > unread > recently viewed > the rest.
    #expect(QuickSwitch.rank(items, query: "muxbar", now: now).map(\.item.id) == ["g", "d", "a", "b"])
    // Empty query: Needs you, Finished, then Recent; sessions only.
    let empty = QuickSwitch.rank(items, query: "", now: now)
    #expect(empty.map(\.item.id) == ["g", "d", "a", "b"])
    #expect(empty.map(\.section) == ["Needs you", "Finished", "Recent", "Recent"])
    #expect(QuickSwitch.rank(items, query: "new", now: now).first?.item.id == "new")
    // At most 9 rows for the empty query.
    let many = (0..<20).map { QuickSwitch.Item(id: "\($0)", title: "s\($0)", lastViewed: now - $0) }
    #expect(QuickSwitch.rank(many, query: "", now: now).count == 9)
    // The first prompt and the folder match too.
    let p = [QuickSwitch.Item(id: "x", title: "s1", folder: "/home/u/ws/payments-api", prompt: "Fix the flaky login test")]
    #expect(QuickSwitch.rank(p, query: "flaky", now: now).count == 1)
    #expect(QuickSwitch.rank(p, query: "payments", now: now).count == 1)
}

@Test func gridColumnsAndTileNavigation() {
    #expect((1...6).map(GridLayout.columns) == [1, 2, 2, 2, 3, 3])
    // 2×2 with 4 tiles: 0 1 / 2 3
    #expect(GridLayout.neighbor(of: 0, count: 4, .right) == 1)
    #expect(GridLayout.neighbor(of: 1, count: 4, .right) == 1)
    #expect(GridLayout.neighbor(of: 1, count: 4, .down) == 3)
    #expect(GridLayout.neighbor(of: 3, count: 4, .up) == 1)
    #expect(GridLayout.neighbor(of: 2, count: 4, .left) == 2)
    // 3 tiles in 2×2: nothing below 1.
    #expect(GridLayout.neighbor(of: 1, count: 3, .down) == 1)
    #expect(GridLayout.neighbor(of: 0, count: 3, .down) == 2)
    // 3×2 with 5 tiles: 0 1 2 / 3 4
    #expect(GridLayout.neighbor(of: 2, count: 5, .down) == 2)
    #expect(GridLayout.neighbor(of: 4, count: 5, .right) == 4)
}

@Test func firstPromptSkipsToolResultsCommandsAndInjectedContext() {
    let claude = """
    {"type":"summary","summary":"x"}
    {"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: The messages below were generated by the user while running local commands."}}
    {"type":"user","message":{"role":"user","content":"<command-name>/model</command-name>"}}
    {"type":"user","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t","content":"ok"}]}}
    {"type":"user","message":{"role":"user","content":[{"type":"text","text":"Fix the flaky login test"}]}}
    {"type":"user","message":{"role":"user","content":"second prompt"}}
    """
    #expect(AgentTranscript.firstUserText(claude, agent: .claude) == "Fix the flaky login test")
    let codex = """
    {"timestamp":"t","type":"session_meta","payload":{"id":"s"}}
    {"timestamp":"t","type":"response_item","payload":{"type":"message","role":"user","content":[{"type":"input_text","text":"<environment_context>cwd</environment_context>"}]}}
    {"timestamp":"t","type":"event_msg","payload":{"type":"user_message","message":"Add a retry to the uploader","images":[]}}
    """
    #expect(AgentTranscript.firstUserText(codex, agent: .codex) == "Add a retry to the uploader")
    #expect(AgentTranscript.firstUserText("not json\n{\"type\":\"assistant\"}", agent: .claude) == nil)
}

@Test func transcriptHeadsComeBackPerPath() async throws {
    let dir = FileManager.default.temporaryDirectory.appendingPathComponent("muxbar-unit-heads-\(UUID().uuidString)")
    try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: dir) }
    let a = dir.appendingPathComponent("a.jsonl"), b = dir.appendingPathComponent("b b.jsonl")
    try #"{"type":"user","message":{"content":"first A"}}"#.write(to: a, atomically: true, encoding: .utf8)
    try #"{"type":"user","message":{"content":"first B"}}"#.write(to: b, atomically: true, encoding: .utf8)
    let n = HostProbe.makeNonce()
    let r = await runProcess("/bin/sh", ["-c", AgentTranscript.headsScript(paths: [a.path, dir.appendingPathComponent("missing").path, b.path], nonce: n)], timeout: 20)
    let heads = AgentTranscript.parseHeads(r.stdout, nonce: n)
    #expect(heads[0].flatMap { AgentTranscript.firstUserText($0, agent: .claude) } == "first A")
    #expect(heads[1].flatMap { AgentTranscript.firstUserText($0, agent: .claude) } == nil)
    #expect(heads[2].flatMap { AgentTranscript.firstUserText($0, agent: .claude) } == "first B")
}
